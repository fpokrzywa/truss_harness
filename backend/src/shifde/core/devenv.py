"""Read/append the development-only env file (`.devdata/dev.env`). Never used in production."""

from __future__ import annotations

from pathlib import Path

from shifde.core.settings import DEV_ENV_FILE


def read_dev_env(path: Path = DEV_ENV_FILE) -> dict[str, str]:
    """KEY=VALUE pairs (last assignment wins); empty if the file does not exist."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def append_dev_env(lines: dict[str, str], path: Path = DEV_ENV_FILE) -> None:
    """Append assignments (a later duplicate key overrides an earlier one when read back)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8-sig") if path.exists() else ""
    sep = "" if existing.endswith("\n") or not existing else "\n"
    with path.open("a", encoding="utf-8", newline="\n") as fh:
        fh.write(sep + "# Generated by shifde dev-sample-data (development only). Do not commit.\n")
        for key, value in lines.items():
            fh.write(f"{key}={value}\n")
