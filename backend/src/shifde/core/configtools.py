"""Configuration tooling: environment JSON Schema, redacted validation of an env file / environment.

Used by `shifde-admin config schema|validate|preflight`. Nothing here prints a secret value:
reports carry variable names and messages only.
"""

from __future__ import annotations

import os
from collections.abc import Iterator, Mapping
from contextlib import contextmanager
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any  # Any: JSON Schema documents

from dotenv import dotenv_values

from shifde.core.settings import (
    SECRET_FIELDS,
    SecretFileError,
    Settings,
    format_validation_error,
    resolve_secret_files,
)

PREFIX = "SHIFDE_"
SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
_SECRET_SCHEMA_NOTE = (
    "Secret: may instead be supplied as {name}_FILE (path of a file holding the value); "
    "setting both is an error."
)


def env_schema() -> dict[str, Any]:  # Any: JSON Schema document
    """JSON Schema of the environment (variable name -> value) understood by the backend."""
    generated = Settings.model_json_schema()
    properties: dict[str, Any] = {}
    for name, sub in generated.get("properties", {}).items():
        var = f"{PREFIX}{name.upper()}"
        entry: dict[str, Any] = {k: v for k, v in sub.items() if k != "title"}
        # Environment values are strings; `type` names the type after parsing.
        entry["description"] = (entry.get("description", "") + " (env value is parsed)").strip()
        if name in SECRET_FIELDS:
            entry["x-secret"] = True
            entry["description"] += " " + _SECRET_SCHEMA_NOTE.format(name=var)
            properties[f"{var}_FILE"] = {
                "type": "string",
                "description": f"Path of a file holding the value of {var} (setting both is an "
                "error). Trailing line breaks are stripped.",
                "x-secret-file": True,
            }
        properties[var] = entry

    def present(name: str) -> dict[str, Any]:
        return {"anyOf": [{"required": [f"{PREFIX}{name.upper()}"]},
                          {"required": [f"{PREFIX}{name.upper()}_FILE"]}]}  # fmt: skip

    return {
        "$schema": SCHEMA_DIALECT,
        "$id": "urn:shifde:env-schema",
        "title": "SHIFDE environment configuration",
        "description": (
            "Generated by `shifde-admin config schema` from the backend settings; do not edit. "
            "SHIFDE_ENV defaults to production when unset."
        ),
        "type": "object",
        "properties": properties,
        "additionalProperties": True,
        "allOf": [
            present("database_url"),
            {
                "if": {
                    "not": {
                        "properties": {f"{PREFIX}ENV": {"enum": ["development", "test"]}},
                        "required": [f"{PREFIX}ENV"],
                    }
                },
                "then": {
                    "allOf": [
                        present("api_key_pepper"),
                        present("secret_keys"),
                        present("metrics_token"),
                        present("public_base_url"),
                    ]
                },
            },
        ],
    }


@dataclass
class ValidationReport:
    ok: bool
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    env: str | None = None
    settings: Settings | None = None  # the validated settings (`config preflight` reads them)

    def render(self) -> str:
        lines = [f"config OK (env={self.env})" if self.ok else "config INVALID"]
        lines += [f"  error: {e}" for e in self.errors]
        lines += [f"  warning: {w}" for w in self.warnings]
        return "\n".join(lines)


@contextmanager
def isolated_environ(values: Mapping[str, str]) -> Iterator[None]:
    """Temporarily replace every SHIFDE_* process variable with `values` (restored on exit), so
    settings are built from exactly that configuration."""
    saved = {k: v for k, v in os.environ.items() if k.startswith(PREFIX)}
    for key in saved:
        del os.environ[key]
    os.environ.update({k: v for k, v in values.items() if k.startswith(PREFIX)})
    try:
        yield
    finally:
        for key in [k for k in os.environ if k.startswith(PREFIX)]:
            del os.environ[key]
        os.environ.update(saved)


def read_env_file(path: Path) -> dict[str, str]:
    """Parse a dotenv-style file (BOM tolerated). Raises OSError if it cannot be read."""
    if not path.is_file():
        raise FileNotFoundError(path)
    return {k: v or "" for k, v in dotenv_values(path, encoding="utf-8-sig").items()}


def validate_environment(environ: Mapping[str, str]) -> ValidationReport:
    """Validate the SHIFDE_* configuration in `environ` exactly as the services would load it."""
    known = {f"{PREFIX}{n.upper()}" for n in Settings.model_fields}
    known |= {f"{k}_FILE" for k in known if k[len(PREFIX) :].lower() in SECRET_FIELDS}
    known.add(f"{PREFIX}MIGRATIONS_DIR")  # read by core.migrations, not a Settings field
    warnings = [
        f"{key}: unknown setting (typo?); it is ignored"
        for key in sorted(environ)
        if key.startswith(PREFIX) and key not in known
    ]
    report = ValidationReport(ok=False, warnings=warnings)
    with isolated_environ(environ):
        try:
            files = resolve_secret_files(environ)
            settings = Settings(_env_file=None, **files)  # type: ignore[arg-type]
        except SecretFileError as exc:
            report.errors.append(str(exc))
            return report
        except ValueError as exc:
            report.errors.append(format_validation_error(exc))
            return report
    report.ok = True
    report.env = settings.env
    report.settings = settings
    if settings.env != "production":
        report.warnings.append(f"SHIFDE_ENV={settings.env}: production guards are not enforced")
    return report
