"""Local PostgreSQL 17 cluster for development and tests (standard library only).

One cluster serves the main checkout and every worktree: its data directory and secrets live in
the MAIN checkout (`<main>/.devdata/pg`, `<main>/.devdata/cluster.env`), found as the parent of
`git rev-parse --git-common-dir`. Each checkout (main or worktree) gets its own application
database and its own `.devdata/dev.env`.

Commands (run from the checkout or worktree root):
  init    create the cluster (port 55450, 127.0.0.1 only, scram-sha-256), start it, create the
          roles, this checkout's database and its dev.env. Idempotent.
  start   start the cluster, then as `env`.
  stop    stop the cluster (every checkout shares it).
  status  exit 0 and print "running on 127.0.0.1:<port>" if the cluster is up, else exit 1.
  env     (cluster running) ensure the roles and this checkout's database `shifde[_<worktree>]`,
          and write `<checkout>/.devdata/dev.env`.

Roles (DECISIONS B-003):
  shifde_owner  LOGIN NOSUPERUSER BYPASSRLS CREATEROLE; owns the databases and the schema objects,
                runs migrations (SHIFDE_MIGRATION_DATABASE_URL). Same attributes as SETH 3ba0e06.
  shifde_app    LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE; owns nothing; what the API
                and worker connect as (SHIFDE_DATABASE_URL).
  postgres      the cluster superuser; tests use it to create throwaway databases
                (SHIFDE_TEST_ADMIN_DATABASE_URL).

Passwords are generated randomly on `init` and kept only in `<main>/.devdata/cluster.env`.
Never print or commit `.devdata/*`.
"""

from __future__ import annotations

import argparse
import os
import re
import secrets
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

PORT = int(os.environ.get("SHIFDE_DEV_DB_PORT", "55450"))
HOST = "127.0.0.1"
SUPERUSER = "postgres"
OWNER_ROLE = "shifde_owner"
APP_ROLE = "shifde_app"
DEFAULT_PG_BIN = Path("C:/Program Files/PostgreSQL/17/bin")
MAX_CONNECTIONS = 600  # pytest -n auto starts one worker per CPU, each with its own pools

# Keys this script owns in dev.env; any other line (e.g. the development pepper and KEK that
# `shifde.core.settings` appends) is kept when the file is rewritten.
MANAGED_KEYS = (
    "SHIFDE_DATABASE_URL",
    "SHIFDE_MIGRATION_DATABASE_URL",
    "SHIFDE_TEST_DATABASE_URL",
    "SHIFDE_TEST_MIGRATION_DATABASE_URL",
    "SHIFDE_TEST_ADMIN_DATABASE_URL",
)
_HEADER = "# Generated by scripts/dev_db.py - LOCAL DEVELOPMENT ONLY. Do not commit."


class DevDbError(Exception):
    pass


# --------------------------------------------------------------------------- locations
def _git(cwd: Path, *args: str) -> str | None:
    try:
        out = subprocess.run(
            ["git", "-C", str(cwd), *args], capture_output=True, text=True, check=True
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip() or None


def checkout_root(cwd: Path | None = None) -> Path:
    """The checkout (main or worktree) the command runs in: git toplevel of the current
    directory, else the checkout holding this script."""
    here = cwd or Path.cwd()
    top = _git(here, "rev-parse", "--show-toplevel")
    return Path(top).resolve() if top else Path(__file__).resolve().parents[1]


def main_root(checkout: Path) -> Path:
    """The main checkout: parent of the shared git directory."""
    common = _git(checkout, "rev-parse", "--path-format=absolute", "--git-common-dir")
    return Path(common).resolve().parent if common else checkout


def database_name(checkout: Path, main: Path) -> str:
    """`shifde` for the main checkout, `shifde_<worktree name>` for a worktree."""
    if checkout == main:
        return "shifde"
    suffix = re.sub(r"[^a-z0-9_]+", "_", checkout.name.lower()).strip("_")[:40]
    return f"shifde_{suffix or 'worktree'}"


class Cluster:
    def __init__(self, main: Path) -> None:
        self.devdata = main / ".devdata"
        self.pgdata = self.devdata / "pg"
        self.secrets_file = self.devdata / "cluster.env"
        self.log_file = self.devdata / "postgres.log"
        self.bin = _pg_bin()

    def tool(self, name: str) -> str:
        exe = self.bin / (f"{name}.exe" if os.name == "nt" else name)
        if not exe.exists():
            raise DevDbError(f"{name} not found in {self.bin} (set PG_BIN)")
        return str(exe)

    # ---------------------------------------------------------------- state
    def initialised(self) -> bool:
        return (self.pgdata / "PG_VERSION").exists()

    def running(self) -> bool:
        if not self.initialised():
            return False
        result = subprocess.run(
            [self.tool("pg_ctl"), "status", "-D", str(self.pgdata)],
            capture_output=True,
            text=True,
        )
        return result.returncode == 0

    def passwords(self) -> dict[str, str]:
        if not self.secrets_file.exists():
            raise DevDbError(f"{self.secrets_file} is missing; run `python scripts/dev_db.py init`")
        values = _read_env(self.secrets_file)
        for key in ("SUPERUSER_PASSWORD", "OWNER_PASSWORD", "APP_PASSWORD"):
            if not values.get(key):
                raise DevDbError(f"{self.secrets_file} lacks {key}; re-create the cluster")
        return values

    # ---------------------------------------------------------------- actions
    def init(self) -> None:
        self.devdata.mkdir(parents=True, exist_ok=True)
        if self.initialised():
            print(f"cluster already initialised at {self.pgdata}")
            return
        if not self.secrets_file.exists():
            _write_private(
                self.secrets_file,
                "# Local PostgreSQL cluster secrets (scripts/dev_db.py). Never commit or print.\n"
                f"SUPERUSER_PASSWORD={_new_password()}\n"
                f"OWNER_PASSWORD={_new_password()}\n"
                f"APP_PASSWORD={_new_password()}\n",
            )
        pw = self.passwords()
        fd, pwfile = tempfile.mkstemp(prefix="pw", dir=self.devdata)
        try:
            with os.fdopen(fd, "w", encoding="ascii") as fh:
                fh.write(pw["SUPERUSER_PASSWORD"])
            subprocess.run(
                [
                    self.tool("initdb"),
                    "-D",
                    str(self.pgdata),
                    "-U",
                    SUPERUSER,
                    f"--pwfile={pwfile}",
                    "--auth=scram-sha-256",
                    "-E",
                    "UTF8",
                    "--locale=C",
                ],
                check=True,
                stdout=subprocess.DEVNULL,
            )
        finally:
            Path(pwfile).unlink(missing_ok=True)
        with (self.pgdata / "postgresql.conf").open("a", encoding="utf-8") as fh:
            fh.write(
                "\n# scripts/dev_db.py\n"
                f"listen_addresses = '{HOST}'\n"
                f"port = {PORT}\n"
                f"max_connections = {MAX_CONNECTIONS}\n"
            )
        print(f"initialised cluster at {self.pgdata}")

    def ready(self) -> bool:
        """True once the server accepts connections (not while it replays WAL after a crash)."""
        result = subprocess.run(
            [self.tool("pg_isready"), "-h", HOST, "-p", str(PORT)],
            capture_output=True,
            text=True,
        )
        return result.returncode == 0

    def wait_ready(self, timeout: float = 3600.0) -> None:
        """Crash recovery of a large cluster takes minutes; `pg_ctl -w` gives up after its -t."""
        deadline = time.monotonic() + timeout
        while not self.ready():
            if not self.running():
                raise DevDbError(f"server stopped during startup; see {self.log_file}")
            if time.monotonic() > deadline:
                raise DevDbError(f"server not accepting connections after {timeout:.0f}s")
            time.sleep(2)

    def start(self) -> None:
        if not self.initialised():
            raise DevDbError("cluster not initialised; run `python scripts/dev_db.py init`")
        if self.running():
            self.wait_ready()
            print(f"already running on {HOST}:{PORT}")
            return
        flags = 0
        if os.name == "nt":
            # A hidden console of its own: the postmaster must not hold this console's handles,
            # and pg_ctl's `cmd /C postgres` must not open a visible window (DETACHED_PROCESS
            # did; closing that window killed the server with ^C).
            flags = subprocess.CREATE_NO_WINDOW | subprocess.CREATE_NEW_PROCESS_GROUP
        subprocess.run(
            [
                self.tool("pg_ctl"),
                "start",
                "-D",
                str(self.pgdata),
                "-l",
                str(self.log_file),
                "-w",
                "-t",
                "60",
            ],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=flags,
            check=False,
        )
        if not self.running():
            raise DevDbError(f"pg_ctl start failed; see {self.log_file}")
        self.wait_ready()
        print(f"started on {HOST}:{PORT}")

    def stop(self) -> None:
        if self.running():
            subprocess.run(
                [self.tool("pg_ctl"), "stop", "-D", str(self.pgdata), "-m", "fast", "-w"],
                check=True,
                stdout=subprocess.DEVNULL,
            )
        print("stopped")

    def psql(self, sql: str, database: str = "postgres", *, query: bool = False) -> str:
        pw = self.passwords()
        env = {**os.environ, "PGPASSWORD": pw["SUPERUSER_PASSWORD"]}
        args = [self.tool("psql"), "-X", "-q", "-v", "ON_ERROR_STOP=1"]
        if query:
            args += ["-tA"]
        args += ["-h", HOST, "-p", str(PORT), "-U", SUPERUSER, "-d", database]
        result = subprocess.run(args, input=sql, capture_output=True, text=True, env=env)
        if result.returncode != 0:
            message = result.stderr.strip()
            for value in pw.values():  # psql echoes the failing statement, passwords included
                message = message.replace(value, "***")
            raise DevDbError(f"psql failed: {message}")
        return result.stdout.strip()

    def ensure_roles(self) -> None:
        pw = self.passwords()
        self.psql(
            f"""
            DO $$ BEGIN
              IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{OWNER_ROLE}') THEN
                CREATE ROLE {OWNER_ROLE} LOGIN;
              END IF;
              IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{APP_ROLE}') THEN
                CREATE ROLE {APP_ROLE} LOGIN;
              END IF;
            END $$;
            ALTER ROLE {OWNER_ROLE} LOGIN NOSUPERUSER BYPASSRLS CREATEROLE NOCREATEDB
              PASSWORD '{pw["OWNER_PASSWORD"]}';
            ALTER ROLE {APP_ROLE} LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE
              NOREPLICATION PASSWORD '{pw["APP_PASSWORD"]}';
            -- {APP_ROLE} is a member of no role: drop any membership granted before
            -- (isolation review 1, item 13). GRANTED BY names each grantor (PostgreSQL 16+).
            DO $$ DECLARE grant_row record; BEGIN
              FOR grant_row IN
                SELECT r.rolname AS granted, g.rolname AS grantor
                  FROM pg_auth_members m
                  JOIN pg_roles r ON r.oid = m.roleid
                  JOIN pg_roles g ON g.oid = m.grantor
                 WHERE m.member = '{APP_ROLE}'::regrole
              LOOP
                EXECUTE format('REVOKE %I FROM %I GRANTED BY %I CASCADE',
                               grant_row.granted, '{APP_ROLE}', grant_row.grantor);
              END LOOP;
            END $$;
            """
        )

    def ensure_database(self, name: str) -> None:
        exists = self.psql(f"SELECT 1 FROM pg_database WHERE datname = '{name}'", query=True)
        if not exists:
            self.psql(f'CREATE DATABASE "{name}" OWNER {OWNER_ROLE}')
        self.psql(
            f'REVOKE ALL ON DATABASE "{name}" FROM PUBLIC;'
            f' GRANT CONNECT, TEMPORARY ON DATABASE "{name}" TO {APP_ROLE};'
        )

    def write_dev_env(self, checkout: Path, db: str) -> Path:
        pw = self.passwords()
        base = f"postgresql+psycopg://{{user}}:{{password}}@{HOST}:{PORT}/{{db}}"
        owner, app = pw["OWNER_PASSWORD"], pw["APP_PASSWORD"]
        values = {
            "SHIFDE_DATABASE_URL": base.format(user=APP_ROLE, password=app, db=db),
            "SHIFDE_MIGRATION_DATABASE_URL": base.format(user=OWNER_ROLE, password=owner, db=db),
            # Tests never use these databases: the harness creates a throwaway database per run
            # and worker and only takes the credentials, host and port from these URLs.
            "SHIFDE_TEST_DATABASE_URL": base.format(user=APP_ROLE, password=app, db=f"{db}_test"),
            "SHIFDE_TEST_MIGRATION_DATABASE_URL": base.format(
                user=OWNER_ROLE, password=owner, db=f"{db}_test"
            ),
            "SHIFDE_TEST_ADMIN_DATABASE_URL": base.format(
                user=SUPERUSER, password=pw["SUPERUSER_PASSWORD"], db="postgres"
            ),
        }
        path = checkout / ".devdata" / "dev.env"
        path.parent.mkdir(parents=True, exist_ok=True)
        kept: list[str] = []
        if path.exists():
            for line in path.read_text(encoding="utf-8-sig").splitlines():
                key = line.split("=", 1)[0].strip()
                if line.strip() == _HEADER or key in MANAGED_KEYS:
                    continue
                kept.append(line)
        body = [_HEADER, *(f"{k}={v}" for k, v in values.items()), *kept]
        _write_private(path, "\n".join(body) + "\n")
        return path


# --------------------------------------------------------------------------- helpers
def _pg_bin() -> Path:
    env_bin = os.environ.get("PG_BIN")
    if env_bin:
        return Path(env_bin)
    if DEFAULT_PG_BIN.exists():
        return DEFAULT_PG_BIN
    found = shutil.which("pg_ctl")
    return Path(found).parent if found else DEFAULT_PG_BIN


def _new_password() -> str:
    return secrets.token_hex(24)


def _read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def _write_private(path: Path, content: str) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    if os.name != "nt":
        path.chmod(0o600)


# --------------------------------------------------------------------------- commands
def cmd_env(cluster: Cluster, checkout: Path, main: Path) -> None:
    if not cluster.running():
        raise DevDbError("cluster is not running; run `python scripts/dev_db.py start`")
    cluster.ensure_roles()
    db = database_name(checkout, main)
    cluster.ensure_database(db)
    path = cluster.write_dev_env(checkout, db)
    print(f"database {db}; wrote {path}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("command", choices=["init", "start", "stop", "status", "env"])
    args = parser.parse_args(argv)
    checkout = checkout_root()
    main_checkout = main_root(checkout)
    cluster = Cluster(main_checkout)
    try:
        if args.command == "status":
            if cluster.running():
                print(f"running on {HOST}:{PORT} (data: {cluster.pgdata})")
                return 0
            state = "stopped" if cluster.initialised() else "not initialised"
            print(f"{state} ({cluster.pgdata})")
            return 1
        if args.command == "stop":
            cluster.stop()
            return 0
        if args.command == "init":
            cluster.init()
        cluster.start()
        cmd_env(cluster, checkout, main_checkout)
    except (DevDbError, subprocess.CalledProcessError) as exc:
        print(f"dev_db: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
